<script>
import axios from "axios";
import mixins from "../mixins";
import BigNumber from "bignumber.js";
import izitoast from "izitoast";

export default {
  name: "Home",
  mixins: [mixins],
  data() {
    return {
      BigNumber,
      projection: {
        plan: null,
        amount: null,
      },
      selectedQuestion: null,
      plans: [],
      priceState: {},
      interval: null,
      faq: [
        {
          question: "How do I invest?",
          answer:
            "Sign up, activate your account, login, make a deposit and commit to an investment plan.",
        },
        {
          question: "What assets do I deposit?",
          answer:
            "You deposit the Ethereum (ETH) equivalent of the US Dollar (USD) amount you wish to invest.",
        },
        {
          question: "Where can I buy Ethereum (ETH) coin?",
          answer:
            'You can buy Ethereum from the following markets: <ul class="mt-2"><li>&rarr; SouthXchange: <a class="text-green-500" href="https://www.southxchange.com/Market/Book/ETH/BTC">ETH/BTC</a></li><li>&rarr; Crex24: <a class="text-green-500" href="https://crex24.com/exchange/ETH-BTC">ETH/BTC</a></li></ul>',
        },
        {
          question: "What is the minimum amount I can invest?",
          answer: `Minimum investment is $<!--MIN_INV-->.`,
        },
        {
          question: "How many simultaneous investments can I make?",
          answer: "As much as you want, regardless of choice of plan.",
        },
        {
          question: "How does the referral program work?",
          answer: "You get 2% of every verified deposit by your referrals.",
        },
        {
          question: "More about ETH-Investment?",
          answer:
            'Check out the following links: <ul class="mt-2"><li>&rarr; <a class="text-green-500" href="https://twitter.com/ethinvest_club/">Twitter</a></li></ul>',
        },
      ],
    };
  },
  computed: {
    selectedPlan() {
      return this.plans.find((p) => p.id === this.projection.plan) || {};
    },

    returns() {
      return this.minCheckFail
        ? "Capital too low!"
        : new BigNumber(this.projection.amount || 0)
            .times(new BigNumber(this.selectedPlan.percentage || 100).div(100))
            .plus(this.projection.amount || 0)
            .toFormat(2);
    },

    minCheckFail() {
      return new BigNumber(this.projection.amount).isLessThan(
        this.selectedPlan.minimumAmount
      );
    },

    minInvestmentAmount() {
      return this.plans.length
        ? new BigNumber(
            this.plans.reduce(
              (min, p) =>
                new BigNumber(p.minimumAmount).isLessThan(min)
                  ? p.minimumAmount
                  : min,
              this.plans[0].minimumAmount
            )
          ).toFormat(0)
        : "...";
    },
  },
  methods: {
    range: function(start, end) {
      return Array(end - start + 1)
        .fill()
        .map((_, idx) => start + idx);
    },

    selectQuestion(index) {
      if (this.selectedQuestion !== index) {
        this.selectedQuestion = index;
      } else {
        this.selectedQuestion = null;
      }
    }
  },

  async mounted() {
    try {
      const res = await axios.get("plans");

      if (res) {
        this.plans.push(...res.data.data);
        this.projection.plan = this.plans.length ? this.plans[0].id : null;
      }
    } catch (err) {
      izitoast.error({
        title: "Error",
        message: "An unknown error occurred.",
      });
    }
  },

  async created() {
    if (this.$route.query.ref) {
      const referrer = sessionStorage.getItem("referrer");

      if (referrer !== null) {
        return;
      }

      const res = await axios.get(`/user/${this.$route.query.ref}`);

      if (res) {
        const referrer = res.data.data.username;

        sessionStorage.setItem("referrer", referrer);
      }
    }
  },

  beforeDestroy() {
    clearInterval(this.interval);
  },
};
</script>
